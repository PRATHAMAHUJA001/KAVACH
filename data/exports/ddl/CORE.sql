create or replace masking policy KAVACH_DB.CORE.MASK_ACCOUNT_NUMBER as (VAL VARCHAR) 
returns VARCHAR ->
CASE
        WHEN CURRENT_ROLE() IN ('KAVACH_ADMIN', 'KAVACH_AUDITOR', 'ACCOUNTADMIN') THEN val
        ELSE CONCAT(REPEAT('X', LENGTH(val) - 4), RIGHT(val, 4))
    END
;
create or replace masking policy KAVACH_DB.CORE.MASK_CUSTOMER_NAME as (VAL VARCHAR) 
returns VARCHAR ->
CASE
        WHEN CURRENT_ROLE() IN ('KAVACH_ADMIN', 'KAVACH_AUDITOR', 'ACCOUNTADMIN') THEN val
        WHEN CURRENT_ROLE() = 'KAVACH_ANALYST' THEN val
        ELSE CONCAT(LEFT(val, 2), REPEAT('*', GREATEST(LENGTH(val) - 2, 0)))
    END
;
create or replace masking policy KAVACH_DB.CORE.MASK_MOBILE as (VAL VARCHAR) 
returns VARCHAR ->
CASE
        WHEN CURRENT_ROLE() IN ('KAVACH_ADMIN', 'KAVACH_AUDITOR', 'ACCOUNTADMIN') THEN val
        WHEN CURRENT_ROLE() = 'KAVACH_ANALYST' THEN val
        ELSE CONCAT(LEFT(val, 3), '****', RIGHT(val, 3))
    END
;
create or replace masking policy KAVACH_DB.CORE.MASK_PAN as (VAL VARCHAR) 
returns VARCHAR ->
CASE
        WHEN CURRENT_ROLE() IN ('KAVACH_ADMIN', 'KAVACH_AUDITOR', 'ACCOUNTADMIN') THEN val
        ELSE 'XXXXX' || SUBSTR(val, 6, 5)
    END
;
create or replace row access policy KAVACH_DB.CORE.RAP_REGION_FILTER as (REGION_VAL VARCHAR) 
returns BOOLEAN ->
CURRENT_ROLE() IN ('ACCOUNTADMIN', 'KAVACH_ADMIN', 'KAVACH_AUDITOR')
    OR EXISTS (
        SELECT 1 FROM KAVACH_DB.CORE.REGION_ACCESS_MAP
        WHERE ROLE_NAME = CURRENT_ROLE()
          AND (REGION = 'ALL' OR REGION = region_val)
    )
;