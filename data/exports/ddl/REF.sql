create or replace secure view KAVACH_DB.REF.COUNTRY_DIM(
	COUNTRY_ID,
	COUNTRY_CODE,
	COUNTRY_CODE_3,
	COUNTRY_NAME,
	COMMON_NAME,
	OFFICIAL_NAME,
	NUMERIC_CODE,
	FLAG
) as
SELECT
    COUNTRY_ID,
    ALPHA_2 AS COUNTRY_CODE,
    ALPHA_3 AS COUNTRY_CODE_3,
    NAME AS COUNTRY_NAME,
    COMMON_NAME,
    OFFICIAL_NAME,
    NUMERIC_CODE,
    FLAG
FROM COUNTRY_DIMENSION.DOURO_DATA.COUNTRY_DIMENSION
WHERE COUNTRY_ID > 0;
create or replace secure view KAVACH_DB.REF.FX_RATES(
	BASE_CURRENCY_ID,
	QUOTE_CURRENCY_ID,
	BASE_CURRENCY_NAME,
	QUOTE_CURRENCY_NAME,
	RATE_DATE,
	RATE
) as
SELECT
    BASE_CURRENCY_ID,
    QUOTE_CURRENCY_ID,
    BASE_CURRENCY_NAME,
    QUOTE_CURRENCY_NAME,
    DATE AS RATE_DATE,
    VALUE AS RATE
FROM SNOWFLAKE_PUBLIC_DATA_FREE.PUBLIC_DATA_FREE.FX_RATES_TIMESERIES
WHERE (BASE_CURRENCY_ID = 'INR' OR QUOTE_CURRENCY_ID = 'INR')
  AND DATE >= '2024-01-01';
create or replace secure view KAVACH_DB.REF.IP_GEO_IPINFO(
	START_IP,
	END_IP,
	START_IP_INT,
	END_IP_INT,
	COUNTRY_CODE,
	COUNTRY_NAME,
	CONTINENT_CODE,
	CONTINENT_NAME,
	ASN,
	AS_NAME,
	AS_DOMAIN
) as
SELECT
    START_IP, END_IP, START_IP_INT, END_IP_INT,
    COUNTRY_CODE, COUNTRY AS COUNTRY_NAME,
    CONTINENT_CODE, CONTINENT AS CONTINENT_NAME,
    ASN, AS_NAME, AS_DOMAIN
FROM IPINFO_LITE.PUBLIC.LITE
WHERE LENGTH(START_IP_INT) <= 16;